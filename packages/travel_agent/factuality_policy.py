def prepare_verification_context(context=None):
    """Preserve supplied audit data without promoting it to a factual verdict."""
    if context is None:
        context = {}
    if not isinstance(context, dict) or not isinstance(context.get('claims', []), list):
        raise ValueError('Verification context must be an object with a claims list')
    return {**context, 'claims': context.get('claims', []),
            'default_source_status': 'uncorroborated', 'default_claim_status': 'unknown'}
